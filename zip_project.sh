#!/bin/bash

# =================================================================
# 脚本名称: zip_project.sh
# 作用: 压缩项目中的网站相关文件，排除开发工具、Git配置等无关文件
# 后期调整建议: 
#   1. 如果后续增加了 css 文件夹，脚本会自动包含（如果使用通配符或目录包含）
#   2. 可以根据需要修改 ZIP_NAME 的前缀
# 设计模式: 过程式脚本
# 学习建议: 
#   - 掌握 zip 命令的 -r (递归) 和 -x (排除) 参数
#   - 了解 shell 脚本中变量定义和日期函数的使用
# =================================================================

# 定义压缩包名称，包含时间戳以防重名
TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
PROJECT_NAME="web_fg_v1"
ZIP_NAME="${PROJECT_NAME}_website_${TIMESTAMP}.zip"

echo "正在准备压缩网站文件..."

# 执行压缩
# 这里我们只包含项目运行所必需的文件和文件夹
zip -r "$ZIP_NAME" \
    *.html \
    css/ \
    js/ \
    images/

if [ $? -eq 0 ]; then
    echo "------------------------------------------------"
    echo "压缩成功！"
    echo "压缩包名称: $ZIP_NAME"
    echo "文件位置: $(pwd)/$ZIP_NAME"
    echo "------------------------------------------------"
else
    echo "压缩过程中出现错误，请检查权限或文件状态。"
    exit 1
fi
